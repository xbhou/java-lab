package dev.xbhou.javalab.spring.tx;

import java.util.List;
import org.springframework.jdbc.core.JdbcTemplate;

public class LedgerRepository {

    private final JdbcTemplate jdbcTemplate;

    public LedgerRepository(JdbcTemplate jdbcTemplate) {
        this.jdbcTemplate = jdbcTemplate;
    }

    public void initialize() {
        jdbcTemplate.execute(
                "drop table if exists tx_event"
        );

        jdbcTemplate.execute(
                """
                create table tx_event (
                    id bigint generated by default as identity primary key,
                    label varchar(200) not null
                )
                """
        );
    }

    public void reset() {
        jdbcTemplate.update("delete from tx_event");
    }

    public void insert(String label) {
        jdbcTemplate.update(
                "insert into tx_event(label) values (?)",
                label
        );

        System.out.println("insert -> " + label);
    }

    public List<String> labels() {
        return jdbcTemplate.queryForList(
                "select label from tx_event order by id",
                String.class
        );
    }
}
